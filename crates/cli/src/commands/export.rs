use clap::Args;
use grat_core::types::config::NetworkConfig;
use grat_core::types::trace::{ContractInvocation, ExecutionTrace};
use std::path::Path;

#[derive(Args)]
pub struct ExportArgs {
    pub tx_hash: String,

    #[arg(long, default_value = "test")]
    pub format: String,

    #[arg(long, short)]
    pub output: Option<String>,
}

fn find_failed_invocation(calls: &[ContractInvocation]) -> Option<&ContractInvocation> {
    calls.iter().find_map(|call| {
        find_failed_invocation(&call.sub_invocations).or_else(|| call.is_error.then_some(call))
    })
}

fn find_custom_error_code(trace: &ExecutionTrace) -> Option<u32> {
    let diagnostics = serde_json::to_string(&trace.diagnostic_events).ok()?;
    let marker = "#";
    let mut rest = diagnostics.as_str();
    while let Some((_, after_marker)) = rest.split_once(marker) {
        let digits: String = after_marker
            .chars()
            .take_while(char::is_ascii_digit)
            .collect();
        if let Ok(code) = digits.parse::<u32>() {
            return Some(code);
        }
        rest = after_marker;
    }
    None
}

fn rust_string(value: &str) -> String {
    format!("{value:?}")
}

fn render_regression_test(
    tx_hash: &str,
    network: &NetworkConfig,
    failure: &ContractInvocation,
    expected_error_code: Option<u32>,
) -> anyhow::Result<String> {
    let network_name = network.network.to_string();
    let network_passphrase = &network.network_passphrase;
    let expected_args = failure
        .arguments
        .iter()
        .map(|arg| format!("{}.to_string()", rust_string(arg)))
        .collect::<Vec<_>>()
        .join(", ");
    let error_assertion = expected_error_code
        .map(|code| {
            format!(
                "    assert!(diagnostics.contains(\"#{code}\"), \"expected contract error #{code}; diagnostics: {{diagnostics}}\");\n"
            )
        })
        .unwrap_or_else(|| {
            "    assert!(!trace.diagnostic_events.is_empty(), \"failed replay should retain diagnostic events\");\n".to_string()
        });

    Ok(format!(
        r#"// Generated by `grat export` from transaction {tx_hash}.
// Run this test with the `grat-core` crate available and access to the selected network.
// Set SOROBAN_RPC_URL, SOROBAN_RPC_API_KEY (if required), and
// SOROBAN_ARCHIVE_URLS (comma-separated) in the test environment.

use grat_core::types::config::{{Network, NetworkConfig}};
use grat_core::types::trace::ContractInvocation;

fn find_failed_invocation(calls: &[ContractInvocation]) -> Option<&ContractInvocation> {{
    calls.iter().find_map(|call| {{
        find_failed_invocation(&call.sub_invocations)
            .or_else(|| call.is_error.then_some(call))
    }})
}}

#[tokio::test]
async fn reproduces_failed_contract_invocation() -> Result<(), Box<dyn std::error::Error>> {{
    let network_name = {network_name:?};
    let network = match network_name {{
        "mainnet" => Network::Mainnet,
        "testnet" => Network::Testnet,
        "futurenet" => Network::Futurenet,
        name => Network::Custom(name.to_string()),
    }};
    let mut network = NetworkConfig::for_network(network);
    network.rpc_url = std::env::var("SOROBAN_RPC_URL")?;
    network.network_passphrase = {network_passphrase:?}.to_string();
    network.api_key = std::env::var("SOROBAN_RPC_API_KEY").ok();
    if let Ok(archive_urls) = std::env::var("SOROBAN_ARCHIVE_URLS") {{
        network.archive_urls = archive_urls.split(',').map(str::to_string).collect();
    }}
    let trace = grat_core::replay::replay_transaction({tx_hash:?}, &network).await?;
    let invocation = find_failed_invocation(&trace.invocations)
        .expect("replay should contain a failed contract invocation");

    assert_eq!(invocation.contract_id, {contract_id:?});
    assert_eq!(invocation.function_name, {function_name:?});
    assert_eq!(invocation.arguments, vec![{expected_args}]);
    assert!(invocation.is_error);

    let diagnostics = serde_json::to_string(&trace.diagnostic_events)?;
{error_assertion}    Ok(())
}}
"#,
        tx_hash = tx_hash,
        contract_id = failure.contract_id,
        function_name = failure.function_name,
    ))
}

pub async fn run(
    args: ExportArgs,
    network: &NetworkConfig,
    output_format: &str,
    quiet: &bool,
) -> anyhow::Result<()> {
    if !*quiet {
        println!(
            "Replaying {} on {:?} to generate a regression test...",
            args.tx_hash, network.network
        );
    }

    let trace = grat_core::replay::replay_transaction(&args.tx_hash, network).await?;
    let failure = find_failed_invocation(&trace.invocations).ok_or_else(|| {
        anyhow::anyhow!("transaction replay completed without a failed contract invocation")
    })?;
    let output_path = args.output.unwrap_or_else(|| {
        format!(
            "grat_test_{}.rs",
            &args.tx_hash[..8.min(args.tx_hash.len())]
        )
    });
    let source = render_regression_test(
        &args.tx_hash,
        network,
        failure,
        find_custom_error_code(&trace),
    )?;
    let path = Path::new(&output_path);
    std::fs::write(path, source.as_bytes()).map_err(|err| {
        anyhow::anyhow!(
            "failed to write regression test to {}: {err}",
            path.display()
        )
    })?;

    if matches!(
        crate::output::OutputFormat::parse(output_format),
        crate::output::OutputFormat::Json
    ) {
        let payload = serde_json::json!({
            "tx_hash": args.tx_hash,
            "network": network.network.to_string(),
            "format": args.format,
            "output_path": output_path,
            "bytes": source.len(),
            "status": "exported",
        });
        println!("{}", serde_json::to_string_pretty(&payload)?);
    } else if !*quiet {
        println!(
            "Regression test written to {output_path} ({} bytes)",
            source.len()
        );
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::{find_custom_error_code, find_failed_invocation, render_regression_test};
    use grat_core::types::trace::{
        ContractInvocation, DiagnosticEvent, ExecutionTrace, ResourceProfile, StateDiff, TraceId,
    };
    use std::collections::HashMap;

    fn failed_invocation() -> ContractInvocation {
        ContractInvocation {
            trace_id: TraceId("trace-1".to_string()),
            contract_id: "C123".to_string(),
            function_name: "transfer".to_string(),
            arguments: vec!["G123".to_string(), "100".to_string()],
            return_value: None,
            host_calls: Vec::new(),
            sub_invocations: Vec::new(),
            total_cpu_instructions: 1,
            total_memory_bytes: 1,
            is_error: true,
        }
    }

    #[test]
    fn exports_the_failed_call_inputs_and_custom_error_assertion() {
        let invocation = failed_invocation();
        let trace = ExecutionTrace {
            tx_hash: "a".repeat(64),
            ledger_sequence: 1,
            network: "testnet".to_string(),
            invocations: vec![invocation.clone()],
            state_diff: StateDiff::default(),
            resource_profile: ResourceProfile::default(),
            diagnostic_events: vec![DiagnosticEvent {
                event_type: "diagnostic".to_string(),
                topics: vec!["Error(Contract, #409)".to_string()],
                data: HashMap::new(),
                timeline_position: 0,
            }],
        };

        assert_eq!(find_custom_error_code(&trace), Some(409));
        assert!(find_failed_invocation(&trace.invocations).is_some());

        let source = render_regression_test(
            &trace.tx_hash,
            &grat_core::types::config::NetworkConfig::testnet(),
            &invocation,
            Some(409),
        )
        .unwrap();
        assert!(source.contains("replay_transaction"));
        assert!(source.contains("SOROBAN_RPC_API_KEY"));
        assert!(!source.contains("soroban-testnet.stellar.org"));
        assert!(source.contains("assert_eq!(invocation.function_name, \"transfer\")"));
        assert!(source.contains(
            "assert_eq!(invocation.arguments, vec![\"G123\".to_string(), \"100\".to_string()])"
        ));
        assert!(source.contains("diagnostics.contains(\"#409\")"));
    }
}
